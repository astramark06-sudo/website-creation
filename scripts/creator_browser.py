"""Browser smoke-check of a verified, original static project.

All HTTP requests are intercepted. Only the generated project is served to
the browser; no URL inputs, external navigation, credentials or public hosting.
"""
from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path
import tempfile

try:
    from .creator_project import assemble, build, filename, read_spec, verify
except ImportError:
    from creator_project import assemble, build, filename, read_spec, verify

ORIGIN = "https://creator.invalid"
VIEWPORTS = (360, 768, 1440)
MIMES = {".html": "text/html; charset=utf-8", ".css": "text/css; charset=utf-8",
         ".js": "text/javascript; charset=utf-8", ".svg": "image/svg+xml"}
ENGINES = ("chromium", "firefox", "webkit")


def check_browser(spec, output=None, engine="chromium", publish=False):
    if engine not in ENGINES:
        raise ValueError("Unsupported browser engine")
    if output is None:
        with tempfile.TemporaryDirectory() as tmp:
            root = Path(tmp) / "site"
            build(spec, root, publish=publish)
            return check_browser(spec, root, engine, publish)
    output = Path(output)
    verify(spec, output, publish=publish)
    # Route only regenerated bytes, which verify has matched with the export.
    files = assemble(spec)
    allowed = {ORIGIN + "/" + name: (body, MIMES[Path(name).suffix])
               for name, body in files.items() if Path(name).suffix in MIMES}
    try:
        from playwright.sync_api import sync_playwright, Error as BrowserError
    except ImportError as exc:
        raise ValueError("Browser checks require the optional Playwright installation.") from exc
    findings = []
    results = []
    expected_pages = [filename(page) for page in spec["pages"]]
    canonical = json.dumps(spec, ensure_ascii=False, sort_keys=True, separators=(",", ":"))
    with sync_playwright() as pw:
        try:
            browser = getattr(pw, engine).launch()
        except BrowserError as exc:
            raise ValueError("Install the selected Playwright browser before testing.") from exc
        version = browser.version
        try:
            for width in VIEWPORTS:
                context = browser.new_context(viewport={"width": width, "height": 900},
                                              service_workers="block", accept_downloads=False)
                blocked = []
                errors = []
                def route_request(route):
                    target = allowed.get(route.request.url)
                    if target is None or route.request.method != "GET":
                        blocked.append("Unexpected network request blocked.")
                        route.abort()
                    else:
                        body, mime = target
                        route.fulfill(status=200, body=body, content_type=mime, headers={
                            "Content-Security-Policy": "default-src 'none'; script-src 'self'; style-src 'self'; connect-src 'none'; base-uri 'none'; form-action 'none'; img-src 'self'; frame-src 'none'",
                            "X-Content-Type-Options": "nosniff",
                        })
                context.route("**/*", route_request)
                try:
                    page = context.new_page()
                    page.set_default_timeout(4000)
                    page.on("pageerror", lambda error: errors.append(("JavaScript: " + str(error))[:400]) if len(errors) < 20 else None)
                    page.on("console", lambda message: errors.append(("Console: " + message.text)[:400]) if message.type == "error" and len(errors) < 20 else None)
                    for item in spec["pages"]:
                        name = filename(item)
                        blocked.clear()
                        errors.clear()
                        checks = {}
                        try:
                            result = page.goto(ORIGIN + "/" + name, wait_until="load", timeout=8000)
                            checks["response"] = bool(result and result.ok)
                            checks["heading"] = (page.locator("h1").count() == 1 and
                                                 page.locator("h1").is_visible() and
                                                 page.locator("h1").text_content() == item["title"].replace("\r\n", "\n").replace("\r", "\n"))
                            checks["landmark"] = page.locator("main#main").count() == 1
                            checks["navigation"] = (
                                page.locator("nav a").evaluate_all("(links) => links.map(a => a.getAttribute('href'))") == expected_pages and
                                page.locator("nav a[aria-current=page]").count() == 1 and
                                page.locator("nav a[aria-current=page]").get_attribute("href") == name
                            )
                            checks["no_horizontal_overflow"] = page.evaluate(
                                "() => document.documentElement.scrollWidth <= window.innerWidth + 1")
                            checks["stylesheet_loaded"] = page.evaluate(
                                "() => !!document.querySelector('link[rel=stylesheet]').sheet")
                            page.keyboard.press("Tab")
                            checks["keyboard_skip_link"] = page.evaluate(
                                "() => document.activeElement?.classList.contains('skip') === true")
                            if checks["keyboard_skip_link"]:
                                page.keyboard.press("Enter")
                                checks["skip_target_focus"] = page.evaluate(
                                    "() => document.activeElement?.id === 'main'")
                            else:
                                checks["skip_target_focus"] = False
                            checks["unique_ids"] = page.evaluate(
                                "() => { const ids = [...document.querySelectorAll('[id]')].map(n=>n.id); return new Set(ids).size===ids.length; }")
                            checks["labeled_form_controls"] = page.evaluate(
                                r"() => [...document.querySelectorAll('input:not([type=hidden]),select,textarea')].every(n=>!!(n.labels?.length || n.getAttribute('aria-label')?.trim() || n.getAttribute('aria-labelledby')?.split(/\s+/).some(id=>document.getElementById(id)?.textContent.trim())))")
                            checks["meaningful_document_metadata"] = page.evaluate(
                                "() => !!(document.documentElement.lang.trim() && document.title.trim() && document.querySelector('meta[name=description]')?.content.trim())")
                            checks["named_buttons_and_links"] = page.evaluate(
                                "() => [...document.querySelectorAll('button,a[href]')].every(n=>!!(n.textContent.trim() || n.getAttribute('aria-label')?.trim()))")
                            details = page.locator("details.component-faq")
                            checks["faq_disclosures"] = True
                            for index in range(details.count()):
                                faq = details.nth(index)
                                faq.locator("summary").click()
                                if not faq.locator("p").is_visible():
                                    checks["faq_disclosures"] = False
                                faq.locator("summary").click()
                            if item["interaction"] == "tasks":
                                page.locator("#task-title").fill("Creator browser check")
                                page.locator("#task-form button").click()
                                checks["task_create"] = page.locator("#tasks li").count() == 1
                                page.get_by_role("button", name="Complete: Creator browser check", exact=True).click()
                                checks["task_complete"] = page.locator("#tasks .done").count() == 1
                                page.reload(wait_until="load")
                                checks["task_persistence"] = page.locator("#tasks .done").count() == 1
                                page.get_by_role("button", name="Remove: Creator browser check", exact=True).click()
                                checks["task_remove"] = page.locator("#tasks li").count() == 0
                            if item["interaction"] == "search":
                                query = page.locator("#section-query")
                                total = len(item["sections"])
                                checks["search_initial"] = page.locator("#page-sections > :not([hidden])").count() == total
                                # A query longer than any generated heading is not assumed absent;
                                # choose a deterministic token that is absent from actual DOM content.
                                absent = "creator-check-no-match"
                                text = page.locator("#page-sections").text_content().lower()
                                while absent in text:
                                    absent += "x"
                                heading = item["sections"][0]["heading"]
                                query.fill(heading)
                                checks["search_positive_result"] = page.locator("#page-sections > *").first.is_visible()
                                query.fill(absent)
                                checks["search_empty_result"] = (
                                    page.locator("#page-sections > :not([hidden])").count() == 0 and
                                    page.locator("#section-search-status").text_content() == f"0 of {total} sections shown."
                                )
                                page.locator("#section-reset").click()
                                checks["search_reset"] = (
                                    page.locator("#page-sections > :not([hidden])").count() == total and
                                    query.input_value() == ""
                                )
                            # Follow one actual internal link (or the current page on a one-page site).
                            next_name = expected_pages[(expected_pages.index(name) + 1) % len(expected_pages)]
                            page.locator(f'nav a[href="{next_name}"]').click()
                            page.wait_for_load_state("load")
                            checks["navigation_click"] = page.url == ORIGIN + "/" + next_name
                        except BrowserError as exc:
                            checks["browser_operation"] = False
                            if len(errors) < 20:
                                errors.append(("Browser operation: " + str(exc))[:400])
                        checks["no_unexpected_requests"] = not blocked
                        checks["no_browser_errors"] = not errors
                        results.append({"page": name, "width": width, "checks": checks, "diagnostics": errors[:20]})
                        findings.extend({"page": name, "width": width, "check": key}
                                        for key, passed in checks.items() if not passed)
                finally:
                    context.close()
        finally:
            browser.close()
    return {
        "version": 1, "status": "failed" if findings else "passed",
        "project_sha256": hashlib.sha256(canonical.encode("utf-8")).hexdigest(),
        "files": {name: hashlib.sha256(body.encode("utf-8")).hexdigest()
                  for name, body in sorted(files.items())},
        "browser": engine, "browser_version": version, "viewports": list(VIEWPORTS),
        "results": results, "findings": findings,
        "limitations": ["Generated static output only; no full-stack or deployed website testing.",
                        "Local route-intercepted smoke checks, not a complete accessibility, performance or security audit.",
                        "No publication approval or deployment is performed."],
    }


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--spec", required=True, type=Path)
    parser.add_argument("--output", type=Path, help="Verify an existing generated output directory")
    parser.add_argument("--engine", choices=ENGINES, default="chromium")
    parser.add_argument("--publish", action="store_true", help="Also require reviewed publication flags")
    parser.add_argument("--report", type=Path, help="Write new evidence file (never overwrite)")
    args = parser.parse_args()
    try:
        report = check_browser(read_spec(args.spec), args.output, args.engine, args.publish)
        data = json.dumps(report, indent=2) + "\n"
        if args.report:
            with args.report.open("x", encoding="utf-8") as stream:
                stream.write(data)
        print(data, end="")
        if report["status"] != "passed":
            raise SystemExit(1)
    except (OSError, ValueError, TypeError, KeyError) as exc:
        parser.error(str(exc))


if __name__ == "__main__":
    main()
